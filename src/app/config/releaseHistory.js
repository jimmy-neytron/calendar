export function mergeReleaseHistory(remoteReleases = []) {
  const validRemote = remoteReleases.filter((item) => /^\d+\.\d+\.\d+$/.test(String(item?.version || '')))
  const byVersion = new Map(validRemote.map((item) => [item.version, item]))
  RELEASE_HISTORY.forEach((item) => byVersion.set(item.version, { ...byVersion.get(item.version), ...item }))
  return [...byVersion.values()].sort((first, second) => compareVersions(second.version, first.version))
}

function release(version, date, title, icon, summary, cards, details) {
  return { id: `release-${version}`, version, date, title, icon, summary, cards, details }
}

function card(title, text, icon) {
  return { title, text, icon }
}

function compareVersions(first, second) {
  const a = first.split('.').map(Number)
  const b = second.split('.').map(Number)
  for (let index = 0; index < 3; index += 1) {
    if (a[index] !== b[index]) return a[index] - b[index]
  }
  return 0
}
